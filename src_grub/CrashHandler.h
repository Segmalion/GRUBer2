// Останній рубіж для "сирих" SEH-винятків (access violation, stack overflow
// тощо), які не впіймав жоден try/catch у програмі. Викликати першим рядком
// у WinMain.
// УВАЖНО: не ловить винятки з конструкторів глобальних об'єктів (curConfig,
// curPC) - вони виконуються ще ДО виклику WinMain, тому цей фільтр фізично
// не встигає встановитися. Саме так стався крах GRUBer.exe 0.3.5.1 (Arm::Arm()
// впав на TDateTime зі значенням "ERROR" ще до появи вікна) - для таких
// випадків потрібен try/catch прямо в конструкторі відповідного класу.
void InstallCrashHandler();

// Дописує рядок у C:\ProgramData\GRUBer\error\crash.log. Чиста файлова
