// Дописує рядок у поточний ротований лог-файл
// C:\ProgramData\GRUBer\logs\logs_<дата початку>.log. Чиста файлова операція
// без залежності від VCL/Form1 (на відміну від printLog/printLogDebug з
// Help.cpp, які й викликають цю функцію для персистенції UI-логу на диск) -
// безпечно викликати з будь-якого потоку.
//
// При першому виклику: створює C:\ProgramData\GRUBer\logs, переносить туди
// застарілі файли з C:\ProgramData\GRUBer\error, і або підхоплює вже
// існуючий незакритий лог-файл, або починає новий. Після 10000 записаних
// рядків поточний файл закривається (перейменовується у
// logs_<початок>_<кінець>.log) і починається новий logs_<новий початок>.log.
void LogFile_Write(const UnicodeString &line);

// Шлях до теки з ротованими лог-файлами (C:\ProgramData\GRUBer\logs\, зі
// зворотним слешем на кінці) - для UI, який показує їх список
// (ComboBox_FileLOGS/RichEdit_FileLOGS на TabSheet_FileLOGS).
UnicodeString LogFile_GetLogDir();
